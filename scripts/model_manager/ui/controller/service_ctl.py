"""Service controller - build, start, stop Gateway and Stargate."""

import asyncio
import logging
import os
import secrets
import signal
from collections.abc import AsyncIterator
from pathlib import Path

from ..model.build_state import BuildState, ImageInfo
from ..model.service_state import ServiceState

logger = logging.getLogger(__name__)

_PGID_KILL_TIMEOUT = 5

_GATEWAY_DIR = Path.home() / ".gateway"
_NODES_DIR = _GATEWAY_DIR / "nodes"


def load_env_file(path: Path) -> dict[str, str]:
    """Parse KEY=VALUE lines from an env file. Shared for TUI and headless relay."""
    entries: dict[str, str] = {}
    if not path.exists():
        return entries
    for line in path.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            entries[key.strip()] = value.strip()
    return entries

